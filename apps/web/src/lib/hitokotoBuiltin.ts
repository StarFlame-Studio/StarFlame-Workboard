export const BUILTIN_SENTENCES: BuiltinSentence[] = RAW.split('\n')
  .map((line) => line.trim())
  .filter(Boolean)
  .map((line) => {
    const [content = '', author = '', origin = ''] = line.split('|')
    return { content: content.trim(), author: author.trim(), origin: origin.trim() }
  })
  .filter((item) => item.content.length > 0)

let lastIndex = -1

/** 随机取一条内置句子，尽量避免与上一条重复 */
export function randomBuiltinSentence(): BuiltinSentence {
  const total = BUILTIN_SENTENCES.length
  if (total === 0) return { content: '把今天交给大屏，把明天交给努力。', author: '星焰作业板', origin: '' }
  let index = Math.floor(Math.random() * total)
  if (total > 1 && index === lastIndex) index = (index + 1) % total
  lastIndex = index
  return BUILTIN_SENTENCES[index]!
}
